"""Index saved reports without running experiments or asserting their validity."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def build(root=ROOT):
    reports = []
    for path in sorted((root / "results").rglob("*.md")):
        if "report" not in path.name.lower() and "summary" not in path.name.lower():
            continue
        text = path.read_text()
        title = next((line.lstrip("# ").strip() for line in text.splitlines()
                      if line.startswith("#")), path.stem)
        reports.append({"path": str(path.relative_to(root)), "title": title,
                        "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
                        "evidence_status": "historical_not_revalidated"})
    (root / "results/catalog.json").write_text(json.dumps(
        {"schema_version": 1, "scope": "saved report inventory, not a leaderboard", "reports": reports},
        ensure_ascii=False, indent=2) + "\n")
    lines = ["# Historical experiment reports", "",
             "Generated by `python scripts/index_results.py`. This inventory preserves",
             "saved reports, not a claim that their scores were independently reproduced.",
             "Read each report's dataset, split, model, judge, denominator and limitations.",
             "Current integration status: [PROJECT_STATUS](../docs/PROJECT_STATUS.md).", ""]
    for row in reports:
        title = row["title"].replace("[", "\\[").replace("]", "\\]")
        lines.append(f"- [{title}]({row['path'].removeprefix('results/')})")
    (root / "results/INDEX.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    build()
